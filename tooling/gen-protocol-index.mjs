// Writes packages/protocol/src/generated/index.ts re-exporting every ts-rs generated type.
// Run after `cargo test -p kalcode-native-core` (which exports the bindings).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_DIR = fileURLToPath(new URL("../packages/protocol/src/generated/", import.meta.url));

function generatedTypes(dir) {
  return readdirSync(dir)
    .filter((file) => file.endsWith(".ts") && file !== "index.ts")
    .map((file) => file.slice(0, -3))
    .sort();
}

// ts-rs inserts spaces before newlines around documented fields. Normalize those
// generator artifacts deterministically so regeneration remains diff-check clean.
// The cargo wrapper also runs this after every `cargo test`, passed or failed: a failing test run
// used to leave raw ts-rs output in the checkout, and the next gate check then refused to run with
// "source changed before check" (gate 37499865413).
export function normalizeGeneratedBindings(dir = GENERATED_DIR) {
  let types;
  try {
    types = generatedTypes(dir);
  } catch {
    return 0;
  }
  let changed = 0;
  for (const name of types) {
    const path = `${dir}${name}.ts`;
    const source = readFileSync(path, "utf8");
    const normalized = source.replace(/[ \t]+(?=\r?$)/gm, "");
    if (normalized !== source) {
      writeFileSync(path, normalized);
      changed += 1;
    }
  }
  return changed;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  normalizeGeneratedBindings();
  const types = generatedTypes(GENERATED_DIR);
  const body = [
    "// Generated by tooling/gen-protocol-index.mjs from Rust types (ts-rs). Do not edit by hand.",
    ...types.map((name) => `export type { ${name} } from "./${name}.ts";`),
    "",
  ].join("\n");

  writeFileSync(`${GENERATED_DIR}index.ts`, body);
  console.log(`protocol: indexed ${types.length} generated types`);
}
