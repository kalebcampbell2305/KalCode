function attrs(props) {
  return Object.entries(props)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${key}="${String(value).replaceAll('"', "&quot;")}"`)
    .join(" ");
}

/** The icon data (name -> SVG body) the generator would write, compared by value in `--check`. */
export async function iconData() {
  const uiRequire = createRequire(join(here, "../../../packages/ui/package.json"));
  const lucideDir = join(dirname(uiRequire.resolve("lucide-react/package.json")), "dist/esm/icons");
  const data = {};
  for (const [name, file] of Object.entries(LIVE_ICONS)) {
    const mod = await import(pathToFileURL(join(lucideDir, `${file}.mjs`)).href);
    data[name] = mod.__iconData.node.map(([tag, props]) => `<${tag} ${attrs(props)}/>`).join("");
  }
  return data;
}

export async function generate() {
  const uiRequire = createRequire(join(here, "../../../packages/ui/package.json"));
  const lucideDir = join(dirname(uiRequire.resolve("lucide-react/package.json")), "dist/esm/icons");
  const version = JSON.parse(readFileSync(uiRequire.resolve("lucide-react/package.json"), "utf8")).version;
  const entries = [];
  for (const [name, file] of Object.entries(LIVE_ICONS)) {
    const mod = await import(pathToFileURL(join(lucideDir, `${file}.mjs`)).href);
    const body = mod.__iconData.node.map(([tag, props]) => `<${tag} ${attrs(props)}/>`).join("");
    entries.push(`  ${name}: ${JSON.stringify(body)},`);
  }
  return [
    `// Generated by scripts/gen-live-icons.mjs from lucide-react ${version} (the version @kalcode/ui uses).`,
    "// Do not edit by hand: run `node scripts/gen-live-icons.mjs`.",
    "export const LIVE_ICON_PATHS = {",
    ...entries,
    "} as const;",
    "",
    "export type LiveIcon = keyof typeof LIVE_ICON_PATHS;",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    // Compare values, not bytes: the formatter may rewrap the committed file.
    const { LIVE_ICON_PATHS } = await import(pathToFileURL(OUT).href);
    if (JSON.stringify(LIVE_ICON_PATHS) !== JSON.stringify(await iconData())) {
      console.error("src/lib/live/icons.ts is out of date: run node scripts/gen-live-icons.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, await generate());
  }
}
