/**
 * Generates src/lib/live/icons.ts: the exact lucide icon geometry the desktop app draws, so the
 * website's live KalCode demo shows the same icons as the app (one source: the lucide-react version
 * @kalcode/ui depends on). The website ships no React; it only reads the icon data at build time.
 *
 *   node scripts/gen-live-icons.mjs          # rewrite the file
 *   node scripts/gen-live-icons.mjs --check  # exit 1 when the committed file has drifted
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "../src/lib/live/icons.ts");

